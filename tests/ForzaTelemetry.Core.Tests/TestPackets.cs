namespace ForzaTelemetry.Core.Tests;

/// <summary>
/// Builds <see cref="TelemetryPacket"/> instances directly (no byte parsing) for engine tests.
/// Engines consume decoded packets, so going through the 324-byte wire format would only add noise;
/// <see cref="Blank"/> is an all-zero packet and tests derive from it with <c>with { ... }</c>.
/// </summary>
internal static class TestPackets
{
    /// <summary>An all-zero packet (IsRaceOn false). Every field of the record is required, hence the long initializer.</summary>
    public static readonly TelemetryPacket Blank = new()
    {
        IsRaceOn = false,
        TimestampMS = 0,
        EngineMaxRpm = 0,
        EngineIdleRpm = 0,
        CurrentEngineRpm = 0,
        AccelerationX = 0,
        AccelerationY = 0,
        AccelerationZ = 0,
        VelocityX = 0,
        VelocityY = 0,
        VelocityZ = 0,
        AngularVelocityX = 0,
        AngularVelocityY = 0,
        AngularVelocityZ = 0,
        Yaw = 0,
        Pitch = 0,
        Roll = 0,
        NormalizedSuspensionTravelFrontLeft = 0,
        NormalizedSuspensionTravelFrontRight = 0,
        NormalizedSuspensionTravelRearLeft = 0,
        NormalizedSuspensionTravelRearRight = 0,
        TireSlipRatioFrontLeft = 0,
        TireSlipRatioFrontRight = 0,
        TireSlipRatioRearLeft = 0,
        TireSlipRatioRearRight = 0,
        WheelRotationSpeedFrontLeft = 0,
        WheelRotationSpeedFrontRight = 0,
        WheelRotationSpeedRearLeft = 0,
        WheelRotationSpeedRearRight = 0,
        WheelOnRumbleStripFrontLeft = 0,
        WheelOnRumbleStripFrontRight = 0,
        WheelOnRumbleStripRearLeft = 0,
        WheelOnRumbleStripRearRight = 0,
        WheelInPuddleFrontLeft = 0,
        WheelInPuddleFrontRight = 0,
        WheelInPuddleRearLeft = 0,
        WheelInPuddleRearRight = 0,
        SurfaceRumbleFrontLeft = 0,
        SurfaceRumbleFrontRight = 0,
        SurfaceRumbleRearLeft = 0,
        SurfaceRumbleRearRight = 0,
        TireSlipAngleFrontLeft = 0,
        TireSlipAngleFrontRight = 0,
        TireSlipAngleRearLeft = 0,
        TireSlipAngleRearRight = 0,
        TireCombinedSlipFrontLeft = 0,
        TireCombinedSlipFrontRight = 0,
        TireCombinedSlipRearLeft = 0,
        TireCombinedSlipRearRight = 0,
        SuspensionTravelMetersFrontLeft = 0,
        SuspensionTravelMetersFrontRight = 0,
        SuspensionTravelMetersRearLeft = 0,
        SuspensionTravelMetersRearRight = 0,
        CarOrdinal = 0,
        CarClass = 0,
        CarPerformanceIndex = 0,
        DrivetrainType = 0,
        NumCylinders = 0,
        CarGroup = 0,
        SmashableVelDiff = 0,
        SmashableMass = 0,
        PositionX = 0,
        PositionY = 0,
        PositionZ = 0,
        Speed = 0,
        Power = 0,
        Torque = 0,
        TireTempFrontLeft = 0,
        TireTempFrontRight = 0,
        TireTempRearLeft = 0,
        TireTempRearRight = 0,
        Boost = 0,
        Fuel = 0,
        DistanceTraveled = 0,
        BestLap = 0,
        LastLap = 0,
        CurrentLap = 0,
        CurrentRaceTime = 0,
        LapNumber = 0,
        RacePosition = 0,
        Accel = 0,
        Brake = 0,
        Clutch = 0,
        HandBrake = 0,
        Gear = 0,
        Steer = 0,
        NormalizedDrivingLine = 0,
        NormalizedAIBrakeDifference = 0,
    };

    /// <summary>
    /// A driving packet: race on, given game time (ms), speed (m/s), cumulative distance (m) and gear.
    /// </summary>
    public static TelemetryPacket Drive(uint timeMs, float speedMs, float distance, byte gear = 1) =>
        Blank with
        {
            IsRaceOn = true,
            TimestampMS = timeMs,
            Speed = speedMs,
            DistanceTraveled = distance,
            Gear = gear,
        };
}
